"""Regenerate docs/tool-reference.md from the live MCP server definition.

python scripts/gen_tool_reference.py
"""

from __future__ import annotations

import tempfile
from pathlib import Path
from typing import Any

import anyio
from mcp import Client

from hantek_mcp.config import load_config
from hantek_mcp.mcp.server import build_server
from hantek_mcp.service import ScopeService

OUT = Path(__file__).resolve().parents[1] / "docs" / "tool-reference.md"
GROUPS = [
    ("Instrument and connection", ["connect", "disconnect", "status", "identify", "get_capabilities",
                                   "get_settings", "get_health"]),
    ("Channels", ["get_channel", "enable_channel", "set_vertical_scale", "set_vertical_offset", "set_coupling",
                  "set_probe_attenuation"]),
    ("Timebase and acquisition", ["set_timebase", "start_acquisition", "stop_acquisition", "single_acquisition",
                                  "wait_for_trigger", "capture", "capture_both_channels",
                                  "get_acquisition_state"]),
    ("Trigger", ["get_trigger", "set_trigger_source", "set_trigger_mode", "set_trigger_slope",
                 "set_trigger_coupling", "set_trigger_level", "force_trigger"]),
    ("Measurements", ["measure_voltage", "measure_frequency", "measure_period", "measure_duty_cycle",
                      "measure_rise_time", "measure_fall_time", "measure_rms", "measure_peak_to_peak",
                      "measure_phase", "measure_channel_delay"]),
    ("Signal processing", ["fft", "spectrum_peaks", "measure_noise", "cross_correlation", "compare_captures",
                           "detect_edges", "detect_pulses"]),
    ("Data and export", ["list_captures", "get_capture_metadata", "get_samples", "get_sample_window",
                         "export_csv", "export_npz", "list_exports", "import_export", "delete_capture",
                         "capture_screenshot"]),
    ("Automation", ["autoset", "find_signal", "measure_repeatedly", "acquire_until", "run_measurement_plan",
                    "abort"]),
    ("Diagnostics and maintenance", ["get_usb_diagnostics", "get_protocol_diagnostics", "run_self_test",
                                     "get_recent_errors", "default_setup", "set_simulated_signal"]),
]  # fmt: skip


def _type(schema: dict[str, Any]) -> str:
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    if "anyOf" in schema:
        return " or ".join(_type(s) for s in schema["anyOf"] if s.get("type") != "null") + " (optional)"
    if schema.get("type") == "array":
        return f"list of {_type(schema.get('items', {}))}"
    if "$ref" in schema:
        return "object"
    return str(schema.get("type", "any"))


def _range(s: dict[str, Any]) -> str:
    parts = []
    for k, sym in (
        ("minimum", ">="),
        ("exclusiveMinimum", ">"),
        ("maximum", "<="),
        ("exclusiveMaximum", "<"),
    ):
        if k in s:
            parts.append(f"{sym} {s[k]}")
    for sub in s.get("anyOf", []):
        parts += [p for p in _range(sub).split(", ") if p]
    return ", ".join(parts)


async def main() -> None:
    with tempfile.TemporaryDirectory() as d:
        svc = ScopeService(
            load_config(overrides={"backend": "simulator", "storage": {"data_dir": d}}, environ={})
        )
        async with Client(build_server(svc)) as c:
            tools = {t.name: t for t in (await c.list_tools()).tools}
            resources = (await c.list_resources()).resources
            templates = (await c.list_resource_templates()).resource_templates
            prompts = (await c.list_prompts()).prompts
    lines = [
        "# MCP tool reference",
        "",
        "Generated by `scripts/gen_tool_reference.py` from the running server definition "
        f"({len(tools)} tools). Every tool returns a JSON object (structured content); failures are returned "
        'as tool errors whose text is `{"error": {"code", "message", "retryable", "details"}}`.',
        "",
        "Annotations: **RO** read-only, **ACQ** acquires/changes acquisition state, **SET** changes instrument "
        "settings (idempotent), **DEL** destructive.",
        "",
    ]
    seen: set[str] = set()
    for title, short in GROUPS:
        lines += [f"## {title}", ""]
        for s in short:
            name = f"scope_{s}"
            t = tools[name]
            seen.add(name)
            a = t.annotations
            tag = "RO" if a and a.read_only_hint else ("DEL" if a and a.destructive_hint else
                                                       ("SET" if a and a.idempotent_hint else "ACQ"))  # fmt: skip
            lines += [f"### `{name}` ({tag})", "", (t.description or "").strip(), ""]
            props = t.input_schema.get("properties", {})
            req = set(t.input_schema.get("required", []))
            if props:
                lines += ["| parameter | type | required | default | constraints | description |",
                          "|---|---|---|---|---|---|"]  # fmt: skip
                for p, s2 in props.items():
                    desc = (s2.get("description") or "").replace("|", "\\|").replace("\n", " ")
                    default = f"`{s2['default']}`" if "default" in s2 else ""
                    lines.append(f"| `{p}` | {_type(s2)} | {'yes' if p in req else ''} | {default} | "
                                 f"{_range(s2)} | {desc} |")  # fmt: skip
                lines.append("")
    missing = set(tools) - seen
    assert not missing, f"tools missing from GROUPS: {missing}"
    lines += ["## Resources", "", "| URI | description |", "|---|---|"]
    lines += [f"| `{r.uri}` | {r.description} |" for r in resources]
    lines += [f"| `{t.uri_template}` | {t.description} |" for t in templates]
    lines += ["", "## Prompts", "", "| prompt | arguments | description |", "|---|---|---|"]
    for p in prompts:
        args = ", ".join(f"`{x.name}`" for x in (p.arguments or [])) or "-"
        lines.append(f"| `{p.name}` | {args} | {p.description} |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(tools)} tools)")


if __name__ == "__main__":
    anyio.run(main)
